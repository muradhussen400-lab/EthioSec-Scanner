"""
EthioSec AI Service.
Handles Ollama communications, timeouts, provider error normalization, and test mocking.
"""

import os
import asyncio
import logging
from typing import Optional, Callable

logger = logging.getLogger("ethiosec.ai")

DEFAULT_TIMEOUT_SECONDS = 30.0

# Optional mock hook for automated tests
_mock_provider: Optional[Callable[[str, str], str]] = None

def set_mock_provider(mock_fn: Optional[Callable[[str, str], str]]):
    """Sets a mock provider function for automated testing."""
    global _mock_provider
    _mock_provider = mock_fn

def get_ollama_config():
    host = os.getenv("OLLAMA_HOST", "http://localhost:11434")
    model = os.getenv("OLLAMA_MODEL", "gemma2")
    return host, model

async def ask_ai(system_context: str, user_message: str, timeout: float = DEFAULT_TIMEOUT_SECONDS) -> str:
    """
    Sends the sanitized context and user message to the AI provider.
    Enforces timeout, error normalization, and authorization context integrity.
    """
    # 1. Check if an active mock is set (used during unit/integration tests)
    if _mock_provider is not None:
        try:
            return _mock_provider(system_context, user_message)
        except Exception as e:
            logger.error(f"Mock AI provider error: {e}")
            return "The AI Assistant encountered an error while processing your request. Please try again later."

    # 2. Get Ollama config
    host, model = get_ollama_config()
    
    # 3. Call Ollama SDK asynchronously with timeout
    try:
        def _call_ollama() -> str:
            try:
                import ollama
            except ImportError:
                return "The ollama package is not installed."
                
            client = ollama.Client(host=host)
            
            try:
                # Check if model exists, if we want to be safe we can just make the request
                # and handle the model not found error
                response = client.chat(
                    model=model,
                    messages=[
                        {"role": "system", "content": system_context},
                        {"role": "user", "content": user_message}
                    ]
                )
                if response and "message" in response and "content" in response["message"]:
                    return response["message"]["content"].strip()
                return "No response generated by the AI assistant."
            except Exception as e:
                err_msg = str(e).lower()
                if "not found" in err_msg or "pull model" in err_msg:
                    return f"The configured Ollama model '{model}' was not found. Please pull it using 'ollama pull {model}'."
                if "connection refused" in err_msg or "connect" in err_msg:
                    return f"Could not connect to Ollama at {host}. Please ensure the service is running."
                raise e

        # Run the synchronous API call in an executor with timeout
        loop = asyncio.get_running_loop()
        reply = await asyncio.wait_for(
            loop.run_in_executor(None, _call_ollama),
            timeout=timeout
        )
        return reply

    except asyncio.TimeoutError:
        logger.warning(f"AI Assistant timed out after {timeout} seconds.")
        return "The AI Assistant request timed out while waiting for a response. Please try again."

    except Exception as e:
        error_msg = str(e)
        logger.error(f"Ollama API invocation error: {error_msg}")
        return "The AI Assistant encountered an error while processing your request. Please try again later."
