"""
EthioSec AI Service.
Handles Google Gemini and Ollama communications, timeouts, provider error normalization, and test mocking.
"""

import os
import asyncio
import logging
from typing import Optional, Callable, List, Dict, Any

logger = logging.getLogger("ethiosec.ai")

DEFAULT_TIMEOUT_SECONDS = 30.0

# Optional mock hook for automated tests
_mock_provider: Optional[Callable[[str, str], str]] = None

def set_mock_provider(mock_fn: Optional[Callable[[str, str], str]]):
    """Sets a mock provider function for automated testing."""
    global _mock_provider
    _mock_provider = mock_fn

def get_ai_provider() -> str:
    """Returns the configured AI provider ('gemini' or 'ollama')."""
    return os.getenv("AI_PROVIDER", "gemini").strip().lower()

def get_gemini_config():
    """Reads Gemini configuration from environment variables."""
    api_key = os.getenv("GEMINI_API_KEY", "").strip()
    model = os.getenv("GEMINI_MODEL", "gemini-3.8-flash").strip()
    return api_key, model

def get_ollama_config():
    """Reads Ollama configuration from environment variables."""
    host = os.getenv("OLLAMA_HOST", "http://localhost:11434").strip()
    model = os.getenv("OLLAMA_MODEL", "gemma2").strip()
    return host, model

async def ask_ai(
    system_context: str,
    user_message: str,
    history: Optional[List[Dict[str, Any]]] = None,
    timeout: float = DEFAULT_TIMEOUT_SECONDS
) -> str:
    """
    Sends the sanitized context and user message to the configured AI provider (Gemini or Ollama).
    Enforces timeout, error normalization, authorization context integrity, and credential safety.
    """
    # 1. Check if an active mock is set (used during unit/integration tests)
    if _mock_provider is not None:
        try:
            return _mock_provider(system_context, user_message)
        except Exception as e:
            logger.error(f"Mock AI provider error: {e}")
            return "The AI Assistant encountered an error while processing your request. Please try again later."

    provider = get_ai_provider()

    # 2. Google Gemini Provider
    if provider == "gemini":
        api_key, model = get_gemini_config()
        if not api_key:
            logger.warning("Gemini API key is not configured in backend environment.")
            return "AI Assistant is currently unavailable: GEMINI_API_KEY is not configured on the server."

        def _call_gemini() -> str:
            try:
                from google import genai
                from google.genai import types
            except ImportError:
                logger.error("google-genai package is not installed.")
                return "The google-genai package is not installed on the server."

            try:
                client = genai.Client(api_key=api_key)

                config = types.GenerateContentConfig(
                    system_instruction=system_context,
                    temperature=0.2,
                )

                # Assemble conversation turns if history is provided
                contents = []
                if history and isinstance(history, list):
                    for turn in history[-6:]:  # Limit to last 6 messages
                        role = turn.get("role")
                        content = turn.get("content")
                        if role and content and isinstance(content, str):
                            genai_role = "user" if role == "user" else "model"
                            contents.append(
                                types.Content(
                                    role=genai_role,
                                    parts=[types.Part.from_text(text=content[:2000])]
                                )
                            )

                # Add the active user question
                contents.append(
                    types.Content(
                        role="user",
                        parts=[types.Part.from_text(text=user_message)]
                    )
                )

                response = client.models.generate_content(
                    model=model,
                    contents=contents,
                    config=config,
                )

                if response and response.text:
                    return response.text.strip()
                return "No response generated by the AI assistant."

            except Exception as e:
                err_str = str(e).lower()
                safe_err_type = type(e).__name__
                # Sanitize error message to ensure no secrets or keys are ever logged
                logger.error(f"Gemini API invocation error ({safe_err_type})")

                if "429" in err_str or "resource_exhausted" in err_str or "quota" in err_str:
                    return "AI Assistant is temporarily rate-limited. Please wait a moment before trying again."
                if "503" in err_str or "unavailable" in err_str or "high demand" in err_str:
                    return "The Gemini AI service is currently experiencing high demand. Please try again shortly."
                if "404" in err_str or "not_found" in err_str or "not found" in err_str:
                    return f"The configured Gemini model '{model}' was not found or is unsupported."
                if "400" in err_str or "403" in err_str or "api_key_invalid" in err_str or "invalid api key" in err_str:
                    return "AI Assistant error: Invalid or unauthorized Gemini API key."
                raise e

        loop = asyncio.get_running_loop()
        try:
            reply = await asyncio.wait_for(
                loop.run_in_executor(None, _call_gemini),
                timeout=timeout
            )
            return reply

        except asyncio.TimeoutError:
            logger.warning(f"AI Assistant Gemini request timed out after {timeout} seconds.")
            return "The AI Assistant request timed out while waiting for a response. Please try again."

        except Exception as e:
            logger.error(f"Gemini request exception: {type(e).__name__}")
            return "The AI Assistant encountered an error while processing your request. Please try again later."

    # 3. Ollama Provider (for local/self-hosted deployment)
    elif provider == "ollama":
        host, model = get_ollama_config()

        def _call_ollama() -> str:
            try:
                import ollama
            except ImportError:
                return "The ollama package is not installed."

            client = ollama.Client(host=host)

            try:
                messages = [{"role": "system", "content": system_context}]
                if history and isinstance(history, list):
                    for turn in history[-6:]:
                        role = turn.get("role")
                        content = turn.get("content")
                        if role and content and isinstance(content, str):
                            ollama_role = "user" if role == "user" else "assistant"
                            messages.append({"role": ollama_role, "content": content[:2000]})

                messages.append({"role": "user", "content": user_message})

                response = client.chat(
                    model=model,
                    messages=messages
                )
                if response and "message" in response and "content" in response["message"]:
                    return response["message"]["content"].strip()
                return "No response generated by the AI assistant."
            except Exception as e:
                err_msg = str(e).lower()
                if "not found" in err_msg or "pull model" in err_msg:
                    return f"The configured Ollama model '{model}' was not found. Please pull it using 'ollama pull {model}'."
                if "connection refused" in err_msg or "connect" in err_msg:
                    return "AI Assistant unavailable — local AI service is not running."
                raise e

        loop = asyncio.get_running_loop()
        try:
            reply = await asyncio.wait_for(
                loop.run_in_executor(None, _call_ollama),
                timeout=timeout
            )
            return reply

        except asyncio.TimeoutError:
            logger.warning(f"AI Assistant Ollama request timed out after {timeout} seconds.")
            return "The AI Assistant request timed out while waiting for a response. Please try again."

        except Exception as e:
            logger.error(f"Ollama API invocation error: {type(e).__name__}")
            return "The AI Assistant encountered an error while processing your request. Please try again later."

    else:
        logger.error(f"Unsupported AI provider configured: {provider}")
        return f"Unsupported AI provider '{provider}' configured on the server."
